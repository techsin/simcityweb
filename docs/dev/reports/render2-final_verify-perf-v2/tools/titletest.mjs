import { readFileSync } from 'node:fs';
import { launch, pickRenderer, gpuPid, serverUrl, procCpu, threadCpu, sleep, guard } from './lib.mjs';
const INIT = readFileSync('./gameinit.js', 'utf8');
const side = process.argv[2] ?? 'new';
const { browser, pid } = await launch();
const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 } });
const page = await ctx.newPage();
await page.addInitScript({ content: 'window.__noDraw = true; window.__drawOn = false;' });
await page.addInitScript({ content: INIT });
const t0 = Date.now();
await page.goto(`${serverUrl(side)}/index.html`, { waitUntil: 'load' });
console.log('load', Date.now() - t0);
await page.waitForFunction(() => window.__ready === true, null, { timeout: 600000, polling: 100 });
console.log('title ready', Date.now() - t0);
guard(pid);
const r = pickRenderer(pid), g = gpuPid(pid);
const a = { m: threadCpu(r), g: procCpu(g), d: await page.evaluate(() => window.__glDraws), f: await page.evaluate(() => window.__frames.length) };
await sleep(10000);
const b = { m: threadCpu(r), g: procCpu(g), d: await page.evaluate(() => window.__glDraws), f: await page.evaluate(() => window.__frames.length) };
console.log('title idle 10 s: main ms', ((b.m - a.m) / 1e6).toFixed(0), 'gpu ms', ((b.g - a.g) / 1e6).toFixed(0), 'draws', b.d - a.d, 'frames', b.f - a.f);
await browser.close();
